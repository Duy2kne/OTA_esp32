export async function calculateSha256(bytes: Uint8Array): Promise<string> {
  // If in browser or Web Crypto environment
  if (typeof crypto !== 'undefined' && crypto.subtle) {
    const hashBuffer = await crypto.subtle.digest('SHA-256', bytes as unknown as BufferSource);
    const hashArray = Array.from(new Uint8Array(hashBuffer));
    return hashArray.map((b) => b.toString(16).padStart(2, '0')).join('');
  }

  // Fallback to node:crypto dynamic import
  const nodeCrypto = await import('node:crypto');
  const hash = nodeCrypto.createHash('sha256');
  hash.update(bytes);
  return hash.digest('hex');
}

/**
 * Standard deviceId rollout hashing function:
 * Jenkins/DJB2-like hash of `${deviceId}:${version}` mod 100
 * Exactly mirrors ESP32 C++ implementation:
 * (hashString(deviceId + version) % 100) < rollout
 */
export function calculateRolloutSlot(deviceId: string, version: string): number {
  const str = `${deviceId}:${version}`;
  let hash = 5381;
  for (let i = 0; i < str.length; i++) {
    hash = ((hash << 5) + hash + str.charCodeAt(i)) >>> 0;
  }
  return hash % 100;
}
